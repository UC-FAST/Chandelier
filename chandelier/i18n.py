"""Small runtime translation layer for the on-device UI.

English is the canonical key language: menu files and code keep their English
labels, and :func:`tr` looks them up in the active language catalog.  Unknown
strings (user-provided menu entries, technical values such as ``JPEG`` or
``1920x1080``) fall back to the original text.
"""

from __future__ import annotations

import logging
from typing import Any

